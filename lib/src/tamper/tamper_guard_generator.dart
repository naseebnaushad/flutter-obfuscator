/// for the honest limitation: everything here can itself be hooked or
/// patched by the same class of tool it looks for. Treat this as raising
/// the bar for casual/automated inspection, not as a real anti-tampering
/// control — pair it with certificate pinning and a dedicated RASP
/// product for anything that actually needs to withstand a targeted
/// attacker.
