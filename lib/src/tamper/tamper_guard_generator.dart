      const needles = ['frida', 'xposed', 'substrate', 'cydia'];
      for (final needle in needles) {
        if (maps.contains(needle)) {
          signals.add(TamperSignal(
              'proc_maps', '/proc/self/maps references "\$needle"'));
          return;
        }
      }
    } catch (_) {
      // /proc/self/maps may be unreadable (SELinux, non-Linux) — that's
      // not itself a signal.
    }
  }

  static Future<bool> _portInUse(int port) async {
    try {
      final socket = await ServerSocket.bind(
        InternetAddress.loopbackIPv4,
        port,
        shared: false,
      ).timeout(const Duration(milliseconds: 300));
      await socket.close();
      return false;
    } catch (_) {
      return true;
    }
