import 'dart:io';

import 'package:path/path.dart' as p;

import '../crypto/key_strategy.dart';

/// Writes `lib/flutter_obfuscator/tamper_guard.g.dart` (v4, opt-in): a
/// best-effort, dependency-free root/jailbreak/Frida heuristic scanner
/// that `SecretVault`/`AssetVault` consult before decrypting anything,
/// when `tamper_detection.enabled: true` in `obfuscator.yaml`.
///
/// This is a static-analysis-tool countermeasure, not an anti-Frida
/// silver bullet: every check here runs in Dart (when [keyStrategy] is
/// [KeyStrategy.dartSplit]) or is reached via a MethodChannel call (for
/// the native strategies), and both of those are themselves hookable by
/// the exact tool this is trying to detect. It raises the cost of a
/// casual/automated pass; it does not stop a reverse engineer willing to
/// patch out the check itself before it runs.
class TamperGuardGenerator {
  static void write({
    required String projectRoot,
    required KeyStrategy keyStrategy,
  }) {
    final dir = Directory(p.join(projectRoot, 'lib', 'flutter_obfuscator'));
    dir.createSync(recursive: true);
    File(p.join(dir.path, 'tamper_guard.g.dart'))
        .writeAsStringSync(_source(keyStrategy));
  }

  static String _source(KeyStrategy keyStrategy) {
    final isNative = keyStrategy.usesNativeChannel;
    final keyImport = isNative ? "\nimport 'native_key_channel.g.dart';" : '';
    final nativeCheck = isNative
        ? '''
    try {
      if (await NativeKeyChannel.isTraced()) {
        signals.add(const TamperSignal(
          'native_traced',
          'native code reports a debugger/tracer attached to this process',
        ));
      }
    } catch (_) {
      // A missing/unregistered plugin shouldn't crash the scan itself —
      // the other heuristics below still run.
    }
'''
        : '';

    return '''
// GENERATED BY flutter_obfuscator. DO NOT EDIT.
// ignore_for_file: type=lint

