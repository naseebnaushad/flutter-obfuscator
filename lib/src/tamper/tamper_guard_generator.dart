/// One root/jailbreak/Frida heuristic that fired.
class TamperSignal {
  const TamperSignal(this.id, this.description);
  final String id;
  final String description;

  @override
  String toString() => id;
}

/// Result of a [TamperGuard.scan] pass.
class TamperReport {
  const TamperReport(this.signals);
  final List<TamperSignal> signals;
  bool get suspicious => signals.isNotEmpty;
}

/// Thrown by `SecretVault`/`AssetVault` when `tamper_detection.mode: block`
/// (the default) and [TamperGuard.scan] found something.
class TamperDetectedException implements Exception {
  TamperDetectedException(this.report);
  final TamperReport report;

  @override
  String toString() =>
      'TamperDetectedException: \${report.signals.map((s) => s.id).join(', ')}';
}

